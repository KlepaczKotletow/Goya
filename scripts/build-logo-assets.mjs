// Generates the two static logo files under public/ from content/logo.ts, so the
// outlines have exactly one source. Run after editing that file:
//
//   node scripts/build-logo-assets.mjs
//
// What it writes:
//   public/logo-goya.svg  the full lockup in brand terracotta. Referenced by the
//                         footer <img> and by Organization JSON-LD `logo`, which
//                         needs a real URL — schema.org will not take inline SVG.
//   public/favicon.svg    the logo's own G on the ink tile.
//
// The outlines themselves came from potrace over the brand's 1280x443 artwork; this
// script only re-frames them, it does not re-trace.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const TERRACOTTA = '#d97757'; // --color-terracotta in app/globals.css
const INK = '#141413'; // --color-ink

/** Pull one `export const NAME = { viewBox: "…", d: "…" }` block out of content/logo.ts. */
function readOutline(source, name) {
  const block = source.match(new RegExp(`export const ${name} = \\{([\\s\\S]*?)\\} as const;`));
  if (!block) throw new Error(`content/logo.ts has no export named ${name}`);
  const field = (key) => {
    const m = block[1].match(new RegExp(`${key}:\\s*"([^"]*)"`));
    if (!m) throw new Error(`${name} has no ${key}`);
    return m[1];
  };
  return { viewBox: field('viewBox'), d: field('d') };
}

const source = fs.readFileSync(path.join(ROOT, 'content/logo.ts'), 'utf8');
const lockup = readOutline(source, 'LOGO_LOCKUP');
const g = readOutline(source, 'LOGO_G');

const write = (file, svg) => {
  fs.writeFileSync(path.join(ROOT, 'public', file), `${svg}\n`);
  console.log(`public/${file} — ${svg.length} bytes`);
};

write(
  'logo-goya.svg',
  `<!-- Generated by scripts/build-logo-assets.mjs from content/logo.ts. Do not hand-edit. -->` +
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${lockup.viewBox}">` +
    `<path fill="${TERRACOTTA}" fill-rule="evenodd" d="${lockup.d}"/>` +
    `</svg>`,
);

// The G is cropped to its own ink, so centring it in the tile is plain arithmetic.
// 39 of 64 units of cap height is ~61% — enough to stay readable at a 16px tab icon.
const TILE = 64;
const CAP = 39;
const scale = CAP / 307;
const dx = (TILE - 288 * scale) / 2;
const dy = (TILE - CAP) / 2;

write(
  'favicon.svg',
  `<!-- Generated by scripts/build-logo-assets.mjs from content/logo.ts. Do not hand-edit. -->` +
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${TILE} ${TILE}">` +
    `<rect width="${TILE}" height="${TILE}" rx="14" fill="${INK}"/>` +
    `<path transform="translate(${dx.toFixed(2)} ${dy.toFixed(2)}) scale(${scale.toFixed(5)})" ` +
    `fill="${TERRACOTTA}" fill-rule="evenodd" d="${g.d}"/>` +
    `</svg>`,
);
